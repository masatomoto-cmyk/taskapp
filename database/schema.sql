CREATE DATABASE IF NOT EXISTS taskapp DEFAULT CHARACTER SET utf8mb4;
USE taskapp;

CREATE TABLE users (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at DATETIME NOT NULL CURRENT_TIMESTAMP
);

CREATE TABLE tasks (
    id INT  NOT NULL AUTO_INCREMENT PRIMARY KEY,
    user_id INT NOT NULL ,
    title VARCHAR(100) NOT NULL, 
    description TEXT ,
    status ENUM('todo','done','expired') NOT NULL DEFAULT 'todo',
    due_date DATE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, 
    updated_at DATETIME NOT NULL ON UPDATE DEFAULT CURRENT_TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE

);
FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE